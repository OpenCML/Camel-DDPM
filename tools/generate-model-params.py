"""Generate transparent, typed Camel parameter-tree operations from one schema."""
import argparse
from pathlib import Path
from model_schema import TYPES, shapes, count

ROOT = Path(__file__).resolve().parents[1]


def source(kind, fields):
    module = "params_" + kind.lower()
    lines = ["// Generated by tools/generate-model-params.py; edit tools/model_schema.py.",
             "module " + module,
             "import { Tensor, randn, zeros, ones, load_npy, sum } from tensor",
             "import { sqrt } from math", "import { Device, upload, download } from tiles",
             "import { adam_leaf } from optim"]
    children = sorted({v for v in fields.values() if isinstance(v, str)})
    for child in children:
        lines.append("import { " + ", ".join([child, "Device" + child, "init" + child, "upload" + child,
            "download" + child, "zero" + child, "step" + child, "ema" + child, "load" + child, "norm" + child, "scale" + child, "distance" + child]) + " } from params_" + child.lower())
    def type_of(value, device=False):
        return ("Device" if device else "") + value if isinstance(value, str) else ("Device<Tensor<f32>>" if device else "Tensor<f32>")
    for device in (False, True):
        name = ("Device" if device else "") + kind
        lines.append("export type " + name + " = { " + ", ".join(k + ": " + type_of(v, device) for k, v in fields.items()) + " }")
    def body(signature, values, effect=False):
        lines.append(signature + (" sync" if effect else "") + " {")
        lines.append("    return { " + ", ".join(k + ": " + v for k, v in values.items()) + " }")
        lines.append("}\n")
    def init_value(value):
        if isinstance(value, str):
            return "init" + value + "()"
        dimensions = str(list(value["shape"]))
        if value["init"] != "normal":
            return value["init"] + "(" + dimensions + ")"
        std = str(value["std"]) if value["std"] is not None else "sqrt(1.0 / " + str(float(value["shape"][0])) + ")"
        return "randn(" + dimensions + ", 0.0, " + std + ")"
    body("export func init" + kind + "(): " + kind, {k: init_value(v) for k, v in fields.items()})
    for op in ("upload", "download", "zero"):
        input_type = "Device" + kind if op == "download" else kind
        output_type = "Device" + kind if op == "upload" else kind
        values = {k: (op + v + "(p." + k + ")" if isinstance(v, str) else
            "p." + k + " * 0.0" if op == "zero" else op + "(p." + k + ")") for k, v in fields.items()}
        body("export func " + op + kind + "(p: " + input_type + "): " + output_type, values, op != "zero")
    body("export func load" + kind + "(path: string): " + kind,
         {k: "load" + v + "(path + '" + k + ".')" if isinstance(v, str)
          else "load_npy(path + '" + k + ".npy') as Tensor<f32>" for k, v in fields.items()}, True)
    body("export func ema" + kind + "(p: " + kind + ", q: " + kind + "): " + kind,
         {k: "ema" + v + "(p." + k + ", q." + k + ")" if isinstance(v, str)
          else "p." + k + " * 0.999 + q." + k + " * 0.001" for k, v in fields.items()})
    body("export func scale" + kind + "(p: " + kind + ", factor: float): " + kind,
         {k: "scale" + v + "(p." + k + ", factor)" if isinstance(v, str)
          else "p." + k + " * factor" for k, v in fields.items()})
    squared = ["norm" + v + "(p." + k + ")" if isinstance(v, str)
               else "sum(p." + k + " * p." + k + ")" for k, v in fields.items()]
    lines += ["export func norm" + kind + "(p: " + kind + "): float {", "    return " + " + ".join(squared), "}", ""]
    squared_delta = ["distance" + v + "(p." + k + ", q." + k + ")" if isinstance(v, str)
        else "sum((p." + k + " - q." + k + ") * (p." + k + " - q." + k + "))" for k, v in fields.items()]
    lines += ["export func distance" + kind + "(p: " + kind + ", q: " + kind + "): float {", "    return " + " + ".join(squared_delta), "}", ""]
    lines.append("export func step" + kind + "(p: " + kind + ", g: " + kind + ", m: " + kind + ", v: " + kind + ", rate: float, bc1: float, bc2: float): (" + kind + ", " + kind + ", " + kind + ") {")
    for k, v in fields.items():
        fn = "step" + v if isinstance(v, str) else "adam_leaf"
        lines.append("    let s_" + k + " = " + fn + "(p." + k + ", g." + k + ", m." + k + ", v." + k + ", rate, bc1, bc2)")
    outputs = ["{ " + ", ".join(k + ": s_" + k + "." + str(i) for k in fields) + " }" for i in range(3)]
    lines += ["    return (" + ", ".join(outputs) + ")", "}", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for kind, fields in TYPES.items():
        path = ROOT / "src" / ("params_" + kind.lower() + ".cml")
        text = source(kind, fields)
        if args.check:
            if path.read_text(encoding="utf-8") != text:
                raise SystemExit("Generated parameter source is stale: " + str(path))
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
        print(kind, "leaves=" + str(len(shapes(kind))), "parameters=" + str(count(kind)))


if __name__ == "__main__":
    main()
